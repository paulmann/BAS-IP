Задаются в `security.rate_limits`. Текущие значения возвращаются в заголовках
`X-RateLimit-Limit`, `X-RateLimit-Remaining`, `X-RateLimit-Reset`.

| Правило | По умолчанию |
|---|---|
| `gate_open` | 20 в минуту |
| `api` | 120 в минуту |
| `status_poll` | 60 в минуту |
| `guest_create` | 10 в минуту |

