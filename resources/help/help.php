## Обновление

**Через интерфейс.** Администрирование → Обновления → «Проверить сейчас» → «Скачать и установить».

**Из консоли.**

```bash
php bin/bas-ip update:check       # есть ли новая версия
php bin/bas-ip update:run         # скачать и установить
php bin/bas-ip update:rollback    # откатиться к снимку
```

Порядок обновления:

1. проверка версии в GitHub (сравнение semver);
2. включение режима обслуживания — интерфейс закрыт, **шлагбаум продолжает работать**;
3. снимок текущих файлов (`storage/app/updates/snapshots/…snapshot`);
4. резервная копия базы данных;
5. скачивание архива, проверка SHA-256 (если задана), распаковка с защитой от zip-slip;
6. копирование файлов поверх текущих;
7. применение новых миграций;
8. очистка кэша, выключение режима обслуживания, запись в аудит.

**Что не затрагивается** (список `update.preserve` в конфиге):

- `.bas-ip.config.local.php`, `config/*.local.php`, `.env`
- `storage/` целиком — логи, кэш, сессии, загрузки, резервные копии, `storage/app/.secrets.php`
- `public/install.lock`
- база данных (миграции только добавляют недостающее)

Поэтому обновление из GitHub **не теряет ваши настройки** — ради этого и нужен локальный конфиг.

## Автоматическое обновление

```php
'update' => [
    'enabled' => true,
    'mode'    => 'auto',      // notify | download | auto
    'channel' => 'stable',    // stable | beta
    'token'   => '${secret:GITHUB_TOKEN}',  // снимает лимит 60 запросов/час
],
```

и в cron:

```cron
15 4 * * * cd /var/www/bas-ip && php bin/bas-ip schedule:run --update --queue >> storage/logs/cron.log 2>&1
```

Режим `auto` устанавливает обновление сам; `notify` только сообщает в интерфейсе и (если настроен)
шлёт уведомление администратору. Перед автообновлением всегда создаётся резервная копия и снимок для отката.

## Миграции

```bash
php bin/bas-ip migrate            # применить новые
php bin/bas-ip migrate:status     # что применено, контрольные суммы
php bin/bas-ip migrate:rollback   # откатить последний пакет
php bin/bas-ip migrate:fresh      # пересоздать схему (ОПАСНО)
```

Схема переносима между MySQL, PostgreSQL и SQLite: различия диалектов (типы, `UPSERT`,
`GROUP_CONCAT`/`STRING_AGG`, `RETURNING`) изолированы в слое `BasIp\Db\Database`.

## Откат версии

При каждом обновлении создаётся снимок файлов. Хранится `update.keep_releases` последних (по умолчанию 5).

```bash
php bin/bas-ip update:snapshots    # список снимков
php bin/bas-ip update:rollback     # откат к предыдущему
```

Если откатывается и схема — восстановите резервную копию базы:
`php bin/bas-ip backup:list` → `php bin/bas-ip backup:restore ID`.
