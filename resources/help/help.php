| Код | Значение |
|---|---|
| 401 | Нет токена или он недействителен |
| 403 | Токену не хватает области доступа |
| 404 | Ресурс не найден |
| 422 | Ошибка валидации или команда отклонена политикой (тихие часы, долг, отключён) |
| 429 | Превышен лимит запросов (есть `Retry-After`) |
