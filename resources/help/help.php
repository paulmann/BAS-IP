4. Скачивается архив; если задана `update.expected_sha256` — проверяется контрольная сумма.
5. Распаковка с **защитой от zip-slip**: любые пути за пределами целевого каталога отклоняются.
6. Копирование файлов поверх текущих, кроме списка `update.preserve`.
7. Применение миграций (`update.auto_migrate`).
8. Очистка кэша, выключение режима обслуживания, запись в аудит.

