## Шифрование секретов

Секреты (`${secret:NAME}`) хранятся в `storage/app/.secrets.php` и шифруются
**AES-256-GCM** ключом приложения, если доступно расширение `sodium`.
Пароли устройств в таблице `devices` шифруются тем же механизмом.

```bash
php bin/bas-ip secret:set DEVICE_PASSWORD
php bin/bas-ip secret:list          # имена и длины, значения не показываются
php bin/bas-ip secret:reencrypt --old-key=…   # после смены app.key
```

Если `app.key` не задан, диагностика выдаст ошибку: без ключа не работают
ни шифрование, ни подписанные ссылки, ни полноценный CSRF.

