### Токен авторизации

Панель выдаёт токен со сроком жизни. Система:

- кеширует токен в базе (`app_state`), файле или кэше — на выбор через `device.token.store`;
- обновляет его **заранее**, до истечения (`token.refresh_skew`, по умолчанию 120 с),
  чтобы первый же запрос после простоя не падал;
- при ответе 401/403 сбрасывает кеш и повторяет запрос один раз;
- после перезагрузки панели принудительно выходит и сбрасывает токен.

### Самоподписанный сертификат

Панели часто живут на `https://192.168.1.50` с самоподписанным сертификатом.
Два варианта:

1. `'device' => ['verify_tls' => false]` — просто и работает во внутренней сети;
2. `'device' => ['ca_bundle' => '/etc/ssl/bas-ip-ca.pem', 'verify_tls' => true]` — правильно.

