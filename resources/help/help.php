## Правило «только активные»

Во всех расчётах, массовых действиях и рассылках участвуют **только активные** жители
(флаг «Включен»). Отключённая запись:

- не попадает в деление суммы обслуживания;
- не получает уведомления;
- не учитывается в статистике дашборда;
- её гостевые доступы автоматически отзываются.

Отдельный флаг «Участвует в оплате» (`is_billed`) позволяет держать жителя активным,
но не включать в смету — например, на время спора о начислениях.

## Ограничение по строкам для жителей

Роль `resident` дополнительно ограничена своей карточкой: даже зная URL, житель не увидит
чужие счета, журнал или гостевые доступы. Проверка выполняется на уровне контроллера
по `resident_id` учётной записи, а не только на уровне маршрутов.

## Режим просмотра от лица жителя

Администратор может открыть кабинет любого жителя ссылкой `/cabinet?as=ID` —
удобно, чтобы воспроизвести проблему «у меня не открывается». Все действия в этом режиме
пишутся в аудит от имени администратора.

## API-токены — отдельно от ролей

Внешние интеграции аутентифицируются токенами с **областями доступа** (scopes), а не ролями.
Токен для Home Assistant с областью `gate.open` не сможет читать базу жителей или менять настройки,
даже если его украдут.
