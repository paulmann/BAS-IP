<?php

declare(strict_types=1);

namespace BasIp\Db;

/**
 * A single column definition with a fluent modifier API.
 */
final class ColumnDefinition
{
    private bool $nullable = false;
    private bool $primary = false;
    private bool $autoIncrement = false;
    private mixed $defaultValue = null;
    private bool $hasDefault = false;
    private bool $unsigned = false;
    private ?string $commentText = null;
    /** @var array<string, mixed> */
    private array $options;

    /** @param array<string, mixed> $options */
    public function __construct(private readonly Database $db, public readonly string $name, private readonly string $type, array $options = [])
    {
        $this->options = $options;
        $this->unsigned = (bool) ($options['unsigned'] ?? false);
        if ($type === 'id') {
            $this->autoIncrement = true;
        }
    }

    public function nullable(bool $nullable = true): self
    {
        $this->nullable = $nullable;

        return $this;
    }

    public function primary(): self
    {
        $this->primary = true;

        return $this;
    }

    public function unsigned(bool $unsigned = true): self
    {
        $this->unsigned = $unsigned;

        return $this;
    }

    public function default(mixed $value): self
    {
        $this->defaultValue = $value;
        $this->hasDefault = true;

        return $this;
    }

    public function comment(string $comment): self
    {
        $this->commentText = mb_substr($comment, 0, 200);

        return $this;
    }

    public function toSql(): string
    {
        $sql = $this->db->quoteIdentifier($this->name) . ' ' . $this->typeSql();

        if ($this->autoIncrement) {
            // Identity handling differs enough per driver that it is inlined here.
            if ($this->db->isMySql()) {
                return $sql . ' AUTO_INCREMENT PRIMARY KEY';
            }
            if ($this->db->isPgsql()) {
                return $sql . ' GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';
            }

            return $sql . ' PRIMARY KEY AUTOINCREMENT';
        }

        if (!$this->nullable) {
            $sql .= ' NOT NULL';
        }
        if ($this->hasDefault) {
            $sql .= ' DEFAULT ' . $this->defaultSql();
        }
        if ($this->primary) {
            $sql .= ' PRIMARY KEY';
        }
        if ($this->commentText !== null && $this->db->isMySql()) {
            $sql .= " COMMENT '" . addslashes($this->commentText) . "'";
        }

        return $sql;
    }

    public function checkSql(): ?string
    {
        if ($this->type !== 'enum') {
            return null;
        }
        $values = (array) ($this->options['values'] ?? []);
        if ($values === []) {
            return null;
        }
        $list = implode(', ', array_map(fn ($v): string => "'" . str_replace("'", "''", (string) $v) . "'", $values));

        return sprintf(
            'CONSTRAINT %s CHECK (%s IN (%s))',
            $this->db->quoteIdentifier($this->name . '_chk'),
            $this->db->quoteIdentifier($this->name),
            $list
        );
    }

    private function typeSql(): string
    {
        $length    = (int) ($this->options['length'] ?? 255);
        $precision = (int) ($this->options['precision'] ?? 12);
        $scale     = (int) ($this->options['scale'] ?? 2);
        $unsigned  = $this->unsigned && $this->db->isMySql() ? ' UNSIGNED' : '';

        return match ($this->type) {
            'id' => match (true) {
                $this->db->isMySql()  => 'BIGINT UNSIGNED',
                $this->db->isPgsql()  => 'BIGINT',
                default               => 'INTEGER',
            },
            'string', 'enum' => sprintf('VARCHAR(%d)', max(1, min(16383, $length))),
            'char'      => sprintf('CHAR(%d)', max(1, min(255, $length))),
            'text'      => $this->db->textType(),
            'boolean'   => $this->db->boolType() . ($this->db->isMySql() ? '(1)' : ''),
            'tinyint'   => 'TINYINT' . $unsigned,
            'smallint'  => 'SMALLINT' . $unsigned,
            'integer'   => 'INTEGER' . $unsigned,
            'bigint'    => 'BIGINT' . $unsigned,
            'decimal'   => sprintf('DECIMAL(%d, %d)', $precision, $scale),
            'float'     => $this->db->isPgsql() ? 'DOUBLE PRECISION' : 'DOUBLE',
            'date'      => $this->db->isSqlite() ? 'TEXT' : 'DATE',
            'datetime'  => $this->db->dateTimeType(),
            'json'      => $this->db->jsonType(),
            'binary'    => match (true) {
                $this->db->isMySql()  => 'LONGBLOB',
                $this->db->isPgsql()  => 'BYTEA',
                default               => 'BLOB',
            },
            default     => 'VARCHAR(255)',
        };
    }

    private function defaultSql(): string
    {
        $value = $this->defaultValue;
        if ($value === null) {
            return 'NULL';
        }
        if (is_bool($value)) {
            return $value ? '1' : '0';
        }
        if (is_int($value) || is_float($value)) {
            return (string) $value;
        }
        if ($value instanceof Expression) {
            return $value->sql;
        }
        $string = (string) $value;
        if (in_array(strtoupper($string), ['CURRENT_TIMESTAMP', 'NOW()', 'NULL'], true)) {
            return strtoupper($string) === 'NOW()' ? $this->db->nowSql() : strtoupper($string);
        }

        return "'" . str_replace("'", "''", $string) . "'";
    }
}
