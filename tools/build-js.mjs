#!/usr/bin/env node
/**
 * build-js.mjs — validate the front-end runtime and refresh the vendored
 * QR-code library.
 *
 *   node tools/build-js.mjs
 *
 * The application scripts (app.js, admin.js, panel.js, guest.js, theme.js)
 * are hand-written ES2020 with no bundler and no transpiler: every evergreen
 * browser since 2020 runs them as-is, and "view source" on a deployed gate
 * controller shows exactly what executes. This script therefore
 *
 *   1. syntax-checks every script with `node --check`;
 *   2. re-vendors qrcode-generator from node_modules into
 *      public/assets/js/vendor/qrcode.js, re-applying the local fix for the
 *      upstream canvas bug (fillRect drew the matrix transposed:
 *      `row * cellSize, col * cellSize` → `col * cellSize, row * cellSize`);
 *   3. regenerates the vendor licence banner with the *actual* package
 *      version so the metadata can never drift again.
 *
 * The build fails loudly if the upstream source no longer matches the patch,
 * so a qrcode-generator bump can never silently reintroduce the bug.
 */

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const jsDir = join(root, 'public', 'assets', 'js');
const vendorDir = join(jsDir, 'vendor');

/* ── 1. syntax-check every application script ───────────────────────────── */

const appScripts = readdirSync(jsDir)
  .filter((f) => f.endsWith('.js'))
  .sort();

if (appScripts.length === 0) {
  console.error('✗ no scripts found in public/assets/js — nothing to check.');
  process.exit(1);
}

let failed = false;
for (const file of appScripts) {
  const res = spawnSync(process.execPath, ['--check', join(jsDir, file)], { encoding: 'utf8' });
  if (res.status !== 0) {
    failed = true;
    console.error(`✗ ${file}: syntax error\n${res.stderr}`);
  }
}
if (failed) process.exit(1);

/* ── 2. vendor qrcode-generator (+ upstream canvas fix) ─────────────────── */

const qrPkgDir = join(root, 'node_modules', 'qrcode-generator');
if (!existsSync(qrPkgDir)) {
  console.error('✗ qrcode-generator not installed — run `npm install` first.');
  process.exit(1);
}
const qrPkg = JSON.parse(readFileSync(join(qrPkgDir, 'package.json'), 'utf8'));
let qrSource = readFileSync(join(qrPkgDir, 'qrcode.js'), 'utf8');

const BUGGY = 'context.fillRect(row * cellSize, col * cellSize, cellSize, cellSize);';
const FIXED = 'context.fillRect(col * cellSize, row * cellSize, cellSize, cellSize);';

if (qrSource.includes(BUGGY)) {
  qrSource = qrSource.replace(BUGGY, FIXED);
} else if (!qrSource.includes(FIXED)) {
  console.error(
    '✗ qrcode-generator source changed: the canvas fillRect patch target was not found.\n' +
    `  Inspect node_modules/qrcode-generator@${qrPkg.version}/qrcode.js, adapt this script,\n` +
    '  then re-run. Refusing to vendor an unpatched (transposed QR) build.',
  );
  process.exit(1);
}

const banner =
  `/* qrcode-generator ${qrPkg.version} — vendored locally (MIT License), with a local fix:\n` +
  ' * the upstream canvas renderer drew the matrix transposed (row/col swapped in fillRect).\n' +
  ' * Regenerated by tools/build-js.mjs — do not edit by hand. */\n';

writeFileSync(join(vendorDir, 'qrcode.js'), banner + qrSource);

/* ── 3. licence banner with the real version ────────────────────────────── */

// The package ships no LICENSE file — embed the MIT text it is distributed under.
const licenseFile = join(qrPkgDir, 'LICENSE');
const mit = existsSync(licenseFile)
  ? readFileSync(licenseFile, 'utf8').trim()
  : [
      'Permission is hereby granted, free of charge, to any person obtaining a copy',
      'of this software and associated documentation files (the "Software"), to deal',
      'in the Software without restriction, including without limitation the rights',
      'to use, copy, modify, merge, publish, distribute, sublicense, and/or sell',
      'copies of the Software, and to permit persons to whom the Software is',
      'furnished to do so, subject to the following conditions:',
      '',
      'The above copyright notice and this permission notice shall be included in all',
      'copies or substantial portions of the Software.',
      '',
      'THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR',
      'IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,',
      'FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE',
      'AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER',
      'LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,',
      'OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE',
      'SOFTWARE.',
    ].join('\n');
writeFileSync(
  join(vendorDir, 'LICENSE-qrcode-generator'),
  `qrcode-generator ${qrPkg.version} — vendored locally (MIT License)\n` +
  'Copyright (c) 2009 Kazuhiko Arase\n' +
  'https://github.com/kazuhikoarase/qrcode-generator\n\n' +
  mit + '\n\n' +
  'Local modification: canvas fillRect row/col transposition fixed (see tools/build-js.mjs).\n\n' +
  'NOTE: bundled locally so the app never depends on a CDN at runtime.\n' +
  'Used to render guest-access QR codes offline.\n',
);

console.log(`✓ js: ${appScripts.length} scripts OK (node --check); vendor/qrcode.js ${qrPkg.version} patched + licenced`);
